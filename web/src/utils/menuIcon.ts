/** 根据菜单 code 或 name 解析出 vue-router 路由名 */
export function resolveRouteName(code?: string | null, menuName?: string): string | undefined {
  if (code) return code
  if (menuName && routeNameFallback[menuName]) return routeNameFallback[menuName]
  return undefined
}
